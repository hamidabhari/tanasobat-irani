const entries=Object.entries(phrases).sort((a,b)=>b[0].length-a[0].length);
const pattern=new RegExp(entries.map(([s])=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g');
export function translate(source){
 let result=source.replace(/یک زمین (.*?) رسم کنید\. از چهار طرف به‌اندازه‌ای حاشیه بدهید که مساحت حاشیه برابر با (.*?)٪ مساحت کل باشد\. سپس همین کار را برای زمین تازه، با حاشیهٔ (.*?)٪ و پس از آن با حاشیهٔ (.*?)٪ تکرار کنید\./g,(_,n,a,b,c)=>`Draw rectangle ${n}. Add an equal-width border on all four sides occupying ${a}% of its area. Repeat inside the resulting rectangle with a ${b}% border, then a ${c}% border.`);
 result=result.replace(pattern,match=>phrases[match]);
 result=result.replace(/([۰-۹\d]+) از ([۰-۹\d]+)/g,'$1 of $2').replace(/([۰-۹\d]+) Rectangle/g,'$1 rectangles');
 return result.replace(/[۰-۹]/g,c=>String('۰۱۲۳۴۵۶۷۸۹'.indexOf(c))).replace(/٪/g,'%').replace(/٫/g,'.').replace(/٬/g,',').replace(/،/g,',').replace(/؛/g,';').replace(/\b1 rectangles\b/g,'1 rectangle');
}
